"""Run the complete per-position IOI analysis and write FINAL_REPORT.md.

    python src/run_position_pipeline.py            # default: results_positional_300 -> results_positional_300_robust

Steps: (1) verify data  (2) per-position stats, Welch+Holm, max-T, object-stratified
(3) same without keys prompts  (4) template-stratified  (5) template/object analysis
(6) stability  (7) final report. No model or network needed; it starts from the saved
positional activations (regenerate them with src/run_experiment_positional.py if needed).
Every number in FINAL_REPORT.md is computed from the outputs of the steps above.
"""
from __future__ import annotations
import argparse, json, subprocess, sys
from pathlib import Path
import numpy as np, pandas as pd

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE))
import analyze_positions_robust as ap


def sh(cmd, quiet=False):
    print("\n$ " + " ".join(map(str, cmd)), flush=True)
    r = subprocess.run([sys.executable, *map(str, cmd)], capture_output=quiet, text=True)
    if r.returncode != 0:
        if quiet: print(r.stdout[-2000:], r.stderr[-2000:])
        sys.exit(f"step failed (exit {r.returncode}): {' '.join(map(str, cmd))}")


def section(path, header):
    t = Path(path).read_text().split("\n"); out = []; on = False
    for line in t:
        if line.startswith("## "):
            if on: break
            on = line.startswith(header)
            continue
        if on: out.append(line)
    return "\n".join(out).strip()


def build_report(a):
    D = Path(a.out); acts = np.load(a.acts, mmap_mode="r"); M = ap.normalize_meta(pd.read_csv(a.meta), acts.shape[1], a.tasks)
    f = M.success.values == 0; N, K, F = acts.shape
    S = pd.read_csv(D / "position_feature_stats_robust.csv"); S0 = pd.read_csv(D / "position_feature_stats_robust_no_keys.csv")
    St = pd.read_csv(D / "position_feature_stats_robust_strat_template.csv")
    tj = json.load(open(D / "template_analysis.json")); sj = json.load(open(D / "stability.json"))
    t = S[S.status == "tested"]; t0 = S0[S0.status == "tested"]; tt = St[St.status == "tested"]
    keys = (M.object == "the keys").values
    L = ["# Per-position IOI SAE analysis: final report", "",
         f"*Generated by `src/run_position_pipeline.py` from `{a.acts}` (GPT-2 small, `gpt2-small-res-jb`, `blocks.8.hook_resid_pre`). "
         "Every number below is computed from the step outputs in this folder.*", "",
         "## 1. Data and verification", "",
         f"{N} prompts, {int(f.sum())} failures, {int((~f).sum())} successes (accuracy {(~f).mean():.3f}); tensor shape {tuple(acts.shape)} "
         "(example, window position, SAE feature). Direction everywhere: **failure minus success**. Verification (`verify_positional_data.py`): all checks passed "
         "(labels equal the original `predictions.csv`; token indices are the true tail of each prompt; the 3-position mean reproduces the original `activations.npy`).", "",
         "## 2. What the positions are", ""]
    for j in range(1, K + 1):
        g = M.groupby(f"pos{j}_token").agg(n=("success", "size"), fails=("success", lambda s: int((s == 0).sum())))
        L.append(f"* **Position {j}** (offset {j - 1 - K}): " + ", ".join(f"`{k}` {int(r.fails)}/{int(r.n)} fail" for k, r in g.sort_values("n", ascending=False).iterrows()))
    L += ["", "Positions are counted from the end of the prompt, not semantic slots. Object identity determines the tokens at positions 1 and 2.", "",
          "## 3. Which features differ between failures and successes", "",
          "| position | tested | Welch+Holm<.05 (higher in failure) | max-T<.05 | stratified by object | stratified by template | |d|>0.8 |", "|---|---:|---:|---:|---:|---:|---:|"]
    for j in range(1, K + 1):
        s = t[t.position == j]; q = tt[tt.position == j]
        L.append(f"| {j} | {len(s)} | {int((s.p_holm < .05).sum())} ({int(((s.p_holm < .05) & (s.delta > 0)).sum())}) | {int((s.p_maxT_perm < .05).sum())} | "
                 f"{int((s.p_maxT_strat < .05).sum())} | {int((q.p_maxT_strat < .05).sum())} | {int((s.cohens_d.abs() > .8).sum())} |")
    L += ["", "Holm is over the complete 3 x 24,576 family. Welch p-values are anti-conservative for sparse features, so the max-T permutation column is the more reliable one. "
          "'Stratified' = labels shuffled only within each object (or template) and activations centred within it: association beyond that variable.", "",
          "### Strongest failure-side features and how closely they track `the keys`", "",
          "| position | feature | d | active in failures / successes | active on keys prompts | active on non-keys prompts | p_holm | p_maxT | p_maxT (object-strat.) |", "|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for j in range(1, K + 1):
        for _, r in t[(t.position == j) & (t.delta > 0)].sort_values("cohens_d", ascending=False).head(5).iterrows():
            x = np.asarray(acts[:, j - 1, int(r.feature)]) > 0
            L.append(f"| {j} | {int(r.feature)} | {r.cohens_d:+.2f} | {int(r.n_fail_active)} / {int(r.n_succ_active)} | {x[keys].sum()}/{keys.sum()} | {x[~keys].sum()}/{(~keys).sum()} | "
                     f"{ap._fmt_p(r.p_holm)} | {ap._fmt_p(r.p_maxT_perm)} | {ap._fmt_p(r.p_maxT_strat)} |")
    L.append("")
    for j in range(1, K + 1):
        rows = t[(t.position == j) & (t.delta > 0)].sort_values("cohens_d", ascending=False).head(5)
        if rows.empty: continue
        act = [np.asarray(acts[:, j - 1, int(r.feature)]) > 0 for _, r in rows.iterrows()]
        n_keyspec = sum(x[keys].mean() >= .95 and x[~keys].mean() <= .02 for x in act)
        n_the = sum(x[M[f"pos{j}_token"].values == " the"].mean() >= .95 and x[M[f"pos{j}_token"].values != " the"].mean() <= .02 for x in act)
        L.append(f"* Position {j}: {n_keyspec} of the top-{len(rows)} are keys-specific (active on >= 95% of keys prompts and <= 2% of others)"
                 + (f"; {n_the} are `the`-specific (active on >= 95% of ` the` prompts and <= 2% of ` a` prompts)." if j == 1 else "."))
    L += ["", f"### Without `the keys` prompts ({int(t0.n_fail.iloc[0])} failures / {int(t0.n_succ.iloc[0])} successes)", "",
          "| position | tested | Welch+Holm<.05 | max-T<.05 | stratified by object | |d|>0.8 |", "|---|---:|---:|---:|---:|---:|"]
    for j in range(1, K + 1):
        s = t0[t0.position == j]
        L.append(f"| {j} | {len(s)} | {int((s.p_holm < .05).sum())} | {int((s.p_maxT_perm < .05).sum())} | {int((s.p_maxT_strat < .05).sum())} | {int((s.cohens_d.abs() > .8).sum())} |")
    surv = t0[t0.p_maxT_perm < .05]
    if len(surv):
        L += ["", "Features passing max-T without keys: " + "; ".join(f"{int(r.feature)} (pos {int(r.position)}, d {r.cohens_d:+.2f}, {'higher in failure' if r.delta > 0 else 'higher in success'})" for _, r in surv.iterrows()) + "."]
    L += ["", "## 4. Averaging vs per-position", "", section(D / "position_vs_average_comparison.md", "## Counts"), "",
          "Overlap, per-feature location of the averaged top features, and hidden/sign-cancelling features: `position_vs_average_comparison.md`.", "",
          "## 5. Template, object and article effects", "",
          f"* Template, all prompts: permutation p = {tj['template_all']['perm_p']:.3f}.",
          f"* Keys prompts only: {tj['template_keys_only']['failures']}/{tj['template_keys_only']['n']} fail, template p = {tj['template_keys_only']['perm_p']:.3f}.",
          f"* Non-keys prompts only: {tj['template_nonkeys']['failures']}/{tj['template_nonkeys']['n']} fail; template p = {tj['template_nonkeys']['perm_p']:.4f}; failures by template {tj['failures_by_template_nonkeys']}.",
          f"* Template {tj['nonkeys_top_template']['template_id']}: {tj['nonkeys_top_template']['fails']}/{tj['nonkeys_top_template']['n']} fail vs "
          f"{tj['nonkeys_top_template']['rest_fails']}/{tj['nonkeys_top_template']['rest_n']} elsewhere (Fisher p = {tj['nonkeys_top_template']['fisher_p']:.2g}); text: `{tj['template_examples'][str(tj['nonkeys_top_template']['template_id'])]}`.",
          "* Details and failure modes: `template_analysis.md`. These tests are post hoc and unadjusted across each other.", "",
          "## 6. Stability", "", "| position | top-20 mean bootstrap recurrence | split-half held-out d (real / label-permuted) | same-sign fraction (real / permuted) |", "|---|---:|---:|---:|"]
    for j in range(1, K + 1):
        o = sj[f"position_{j}"]; s = o["split_half_fail_side"]
        L.append(f"| {j} | {o['top_k_mean_recurrence']:.2f} | {s['mean_d_heldout_real']:+.2f} / {s['mean_d_heldout_label_permuted']:+.2f} | {s['frac_same_sign_real']:.2f} / {s['frac_same_sign_label_permuted']:.2f} |")
    wt = [min(min(r["within_template_d"]) for r in sj[f"position_{j}"]["top_failure_features"]) for j in range(1, K + 1)]
    lo = [min(r["min_d_leave_one_template_out"] for r in sj[f"position_{j}"]["top_failure_features"]) for j in range(1, K + 1)]
    L += ["", "Top-5 failure-side features per position, smallest d within any single template: " + ", ".join(f"position {j}: {v:+.2f}" for j, v in enumerate(wt, 1))
          + "; smallest d when any one template is left out: " + ", ".join(f"position {j}: {v:+.2f}" for j, v in enumerate(lo, 1)) + "."]
    L += ["", "Stability here means the finding is reproducible within this 300-prompt sample (and across templates, see `stability.md`); it does not mean it is causal or independent of the object confound. A fresh-seed corpus needs the model (`build_task_set.py --seed`, then the positional runner).", "",
          "## 7. Conclusions supported by these outputs", ""]
    so = int(t.p_maxT_strat.lt(.05).sum()); sk = int(tt.p_maxT_strat.lt(.05).sum()); nm = int(t[(t.position > 1) & (t.p_maxT_perm < .05) & (t.delta > 0)].shape[0])
    L.append(f"* Unstratified, {nm} failure-higher features at positions 2-3 pass max-T; the strongest are active almost exactly on the keys prompts (table in section 3).")
    L.append(f"* Stratified by object: {so} features (any position) remain significant" + (" -- no evidence of association beyond object identity in this sample." if so == 0 else ": see `position_feature_stats_robust.csv` (p_maxT_strat)."))
    top23 = t[(t.position > 1) & (t.delta > 0)].sort_values("cohens_d", ascending=False).groupby("position").head(5)
    chk = tt.merge(top23[["feature", "position"]], on=["feature", "position"])
    L.append(f"* Stratified by template (labels shuffled within template): {sk} features significant overall; "
             f"{int((chk.p_maxT_strat < .05).sum())} of the {len(top23)} strongest position-2/3 failure features remain significant, so these are not a template artifact.")
    L += ["", "## 8. Limitations", "",
          f"* Only {int(t0.n_fail.iloc[0])} failures outside keys and {int((~f & keys).sum())} successes inside keys: the stratified tests have low power; 'not significant' is not 'absent'.",
          "* One model, SAE, layer and task; 300 prompts from one generator; associations only, no causal claim (ablations are not re-run here).",
          "* Last-3 positions are end-relative; token identity is part of what is measured.", "",
          "## Files", "", "`position_feature_stats_robust*.csv`, `top_features_by_position_robust*.md`, `position_effects_robust*.png`, `position_vs_average_comparison*.md`, `template_analysis.md/json`, `stability.md/json`, `FINAL_REPORT.md`."]
    (D / "FINAL_REPORT.md").write_text("\n".join(L) + "\n"); print(f"\nwrote {D / 'FINAL_REPORT.md'}")


def main():
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("--acts", default="results_positional_300/positional_activations.npy")
    p.add_argument("--meta", default="results_positional_300/positional_metadata.csv")
    p.add_argument("--tasks", default="data/tasks.jsonl")
    p.add_argument("--out", default="results_positional_300_robust")
    p.add_argument("--permutations", type=int, default=2000)
    a = p.parse_args()
    D = Path(a.out); D.mkdir(parents=True, exist_ok=True)
    base = ["--acts", a.acts, "--meta", a.meta, "--tasks", a.tasks, "--permutations", a.permutations,
            "--out-stats", D / "position_feature_stats_robust.csv", "--out-top", D / "top_features_by_position_robust.md",
            "--out-fig", D / "position_effects_robust.png", "--out-compare", D / "position_vs_average_comparison.md"]
    sh([HERE / "verify_positional_data.py", "--acts", a.acts, "--meta", a.meta, "--tasks", a.tasks])
    sh([HERE / "analyze_positions_robust.py", *base, "--stratify-by", "object"])
    sh([HERE / "analyze_positions_robust.py", *base, "--stratify-by", "object", "--exclude-object", "the keys", "--suffix", "_no_keys"])
    sh([HERE / "analyze_positions_robust.py", *base, "--stratify-by", "template_id", "--suffix", "_strat_template"])
    sh([HERE / "analyze_templates.py", "--meta", a.meta, "--tasks", a.tasks, "--out", D])
    sh([HERE / "stability_positions.py", "--acts", a.acts, "--meta", a.meta, "--tasks", a.tasks, "--out", D])
    build_report(a)


if __name__ == "__main__":
    main()
